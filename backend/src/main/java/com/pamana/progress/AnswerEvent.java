package com.pamana.progress;

import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * One row per answer attempt.
 *
 * <p>Progress rows ({@code word_mastery}, {@code syllable_progress},
 * {@code sentence_progress}) only hold the latest result per item, so a wrong
 * answer that is later corrected leaves no trace. This log is append-only:
 * every attempt is kept, which lets the app compute
 * {@code correct items / total items} without ever decreasing, and lets the
 * team measure wrong-attempts-per-item and replay usage.
 */
@Entity
@Table(name = "answer_events")
public class AnswerEvent {

    @Id
    @GeneratedValue(strategy = GenerationType.AUTO)
    private UUID id;

    @NotNull
    @Column(name = "user_id", nullable = false)
    private UUID userId;

    /**
     * Groups every answer of one play-through / practice run. Generated by the
     * client when the screen mounts so a bar can be recomputed from the server.
     */
    @NotNull
    @Column(name = "run_id", nullable = false)
    private UUID runId;

    /** {@code module} or {@code practice}. */
    @NotBlank
    @Column(nullable = false, length = 16)
    private String activity;

    /** {@code vocabulary_word}, {@code syllable_set} or {@code sentence_task}. */
    @NotBlank
    @Column(name = "item_type", nullable = false, length = 24)
    private String itemType;

    /** Word UUID, {@code subLevel:setId}, or sentence task UUID. */
    @NotBlank
    @Column(name = "item_key", nullable = false, length = 80)
    private String itemKey;

    /** pakinggan / kilalanin / basahin / gamitin / pagsama / ... */
    @Column(length = 16)
    private String step;

    @Column(name = "module_number")
    private Integer moduleNumber;

    /** 1-based attempt number for this item within this run. */
    @NotNull
    @Column(name = "attempt_number", nullable = false)
    private Integer attemptNumber;

    @NotNull
    @Column(name = "is_correct", nullable = false)
    private Boolean correct;

    @NotNull
    @Column(name = "answered_at", nullable = false)
    private LocalDateTime answeredAt;

    public AnswerEvent() {
    }

    public AnswerEvent(UUID userId, UUID runId, String activity, String itemType, String itemKey,
            String step, Integer moduleNumber, Integer attemptNumber, Boolean correct) {
        this.userId = userId;
        this.runId = runId;
        this.activity = activity;
        this.itemType = itemType;
        this.itemKey = itemKey;
        this.step = step;
        this.moduleNumber = moduleNumber;
        this.attemptNumber = attemptNumber;
        this.correct = correct;
    }

    @PrePersist
    protected void onCreate() {
        if (this.answeredAt == null) {
            this.answeredAt = LocalDateTime.now();
        }
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public UUID getRunId() {
        return runId;
    }

    public void setRunId(UUID runId) {
        this.runId = runId;
    }

    public String getActivity() {
        return activity;
    }

    public void setActivity(String activity) {
        this.activity = activity;
    }

    public String getItemType() {
        return itemType;
    }

    public void setItemType(String itemType) {
        this.itemType = itemType;
    }

    public String getItemKey() {
        return itemKey;
    }

    public void setItemKey(String itemKey) {
        this.itemKey = itemKey;
    }

    public String getStep() {
        return step;
    }

    public void setStep(String step) {
        this.step = step;
    }

    public Integer getModuleNumber() {
        return moduleNumber;
    }

    public void setModuleNumber(Integer moduleNumber) {
        this.moduleNumber = moduleNumber;
    }

    public Integer getAttemptNumber() {
        return attemptNumber;
    }

    public void setAttemptNumber(Integer attemptNumber) {
        this.attemptNumber = attemptNumber;
    }

    public Boolean getCorrect() {
        return correct;
    }

    public void setCorrect(Boolean correct) {
        this.correct = correct;
    }

    public LocalDateTime getAnsweredAt() {
        return answeredAt;
    }

    public void setAnsweredAt(LocalDateTime answeredAt) {
        this.answeredAt = answeredAt;
    }
}
