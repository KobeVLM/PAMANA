package com.pamana.progress;

import jakarta.persistence.*;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;

import java.time.LocalDateTime;
import java.util.UUID;

/**
 * One tap of an in-game "Makinig Ulit" replay button.
 *
 * <p>Kept separate from {@link AnswerEvent} so a replay never changes attempt
 * numbers or the honest answer-based progress bar. This log is the in-app
 * telemetry required by the Priority 2 refactoring: it answers how often each
 * learner asked to hear an instruction or target word again.
 */
@Entity
@Table(name = "replay_events")
public class ReplayEvent {

    @Id
    @GeneratedValue(strategy = GenerationType.AUTO)
    private UUID id;

    @NotNull
    @Column(name = "user_id", nullable = false)
    private UUID userId;

    /** Groups replays from one screen mount; generated by the client. */
    @NotNull
    @Column(name = "run_id", nullable = false)
    private UUID runId;

    /** {@code module} or {@code practice}. */
    @NotBlank
    @Column(nullable = false, length = 16)
    private String activity;

    /** {@code npc_instruction}, {@code target_word}, {@code target_sentence}, ... */
    @NotBlank
    @Column(name = "item_type", nullable = false, length = 24)
    private String itemType;

    /** Stable identifier for the audio, e.g. the asset path. */
    @NotBlank
    @Column(name = "item_key", nullable = false, length = 120)
    private String itemKey;

    @Column(length = 16)
    private String step;

    @Column(name = "module_number")
    private Integer moduleNumber;

    /** Which control was tapped: {@code npc}, {@code target}, {@code scaffold}. */
    @NotBlank
    @Column(nullable = false, length = 24)
    private String source;

    @NotNull
    @Column(name = "replayed_at", nullable = false)
    private LocalDateTime replayedAt;

    public ReplayEvent() {
    }

    public ReplayEvent(UUID userId, UUID runId, String activity, String itemType,
            String itemKey, String step, Integer moduleNumber, String source) {
        this.userId = userId;
        this.runId = runId;
        this.activity = activity;
        this.itemType = itemType;
        this.itemKey = itemKey;
        this.step = step;
        this.moduleNumber = moduleNumber;
        this.source = source;
    }

    @PrePersist
    protected void onCreate() {
        if (this.replayedAt == null) {
            this.replayedAt = LocalDateTime.now();
        }
    }

    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public UUID getUserId() {
        return userId;
    }

    public void setUserId(UUID userId) {
        this.userId = userId;
    }

    public UUID getRunId() {
        return runId;
    }

    public void setRunId(UUID runId) {
        this.runId = runId;
    }

    public String getActivity() {
        return activity;
    }

    public void setActivity(String activity) {
        this.activity = activity;
    }

    public String getItemType() {
        return itemType;
    }

    public void setItemType(String itemType) {
        this.itemType = itemType;
    }

    public String getItemKey() {
        return itemKey;
    }

    public void setItemKey(String itemKey) {
        this.itemKey = itemKey;
    }

    public String getStep() {
        return step;
    }

    public void setStep(String step) {
        this.step = step;
    }

    public Integer getModuleNumber() {
        return moduleNumber;
    }

    public void setModuleNumber(Integer moduleNumber) {
        this.moduleNumber = moduleNumber;
    }

    public String getSource() {
        return source;
    }

    public void setSource(String source) {
        this.source = source;
    }

    public LocalDateTime getReplayedAt() {
        return replayedAt;
    }

    public void setReplayedAt(LocalDateTime replayedAt) {
        this.replayedAt = replayedAt;
    }
}
